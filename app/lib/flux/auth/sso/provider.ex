defmodule Flux.Auth.SSO.Provider do
  @moduledoc """
  Contract for single sign-on providers.

  Community ships `Flux.Auth.SSO.Providers.Community`, which reports SSO as
  unavailable, never enforces it and refuses configuration writes. An
  alternative provider is supplied at runtime once `:sso` is entitled.

  ## What stays on this side of the contract

  The public repo owns everything a request touches: the routes, the signed
  hand-off between the identity provider's callback and the browser's session,
  session creation, enforcement at the password and magic-link entry points,
  session revocation and the settings UI. A provider owns protocol handling,
  configuration storage, domain verification, and turning a validated assertion
  into a `Flux.Accounts.User` (linking an existing account or creating one).

  ## Identifiers and URLs

  A configuration is addressed by an opaque, URL-safe `config_id` that never
  changes for the life of the configuration (it is not the organization slug,
  which can be renamed). Routes are fixed by this repo:

    * `/sso/:config_id/acs` - the assertion consumer service (HTTP-POST binding)
    * `/sso/:config_id/metadata` - service-provider metadata

  Providers receive absolute URLs from the caller rather than building them, so
  they never depend on endpoint configuration. The one exception is the
  service-provider entity ID, which a provider derives once from `base_url` when
  a configuration is created and then keeps: identity providers key their
  integration on it, so it must survive a later change of host.

  ## Failure contract

  Every callback must be total. Return `false`, `:none`, `[]` or an `{:error, _}`
  rather than raising — these run on the sign-in page, where an exception locks
  everybody out.
  """

  alias Flux.Accounts.User
  alias Flux.Auth.SSO.{Config, Domain}

  @typedoc "Opaque, stable, URL-safe identifier for a configuration."
  @type config_id :: String.t()

  @typedoc """
  Field-level errors for a rejected write. A keyword list rather than an
  `Ecto.Changeset`, because the schema lives behind this contract.
  """
  @type errors :: [{atom(), String.t()}]

  @typedoc """
  Parameters for starting a sign-in.

    * `:request_id` - the ID to put on the authentication request. It is
      generated by the caller, valid as an XML `ID`, and comes back as
      `InResponseTo`.
    * `:relay_state` - an opaque value to round-trip through the identity
      provider. At most 80 bytes.
    * `:acs_url` - the absolute assertion consumer service URL.
  """
  @type authn_params :: %{
          request_id: String.t(),
          relay_state: String.t(),
          acs_url: String.t()
        }

  @typedoc """
  Parameters for consuming a response posted to the assertion consumer service.

    * `:response` - the raw, still-encoded protocol response.
    * `:request_id` - the request ID this response must answer. Responses that
      answer anything else, or nothing (unsolicited), must be rejected.
    * `:acs_url` - the absolute URL the response was posted to; it must match the
      response's destination.
  """
  @type consume_params :: %{
          response: String.t(),
          request_id: String.t(),
          acs_url: String.t()
        }

  @doc """
  Whether any organization has a usable configuration (one verified domain at
  least). Drives whether the sign-in page offers single sign-on at all.
  """
  @callback available?() :: boolean()

  @doc """
  Resolves a work email address to the configuration that owns its domain.

  Only verified domains may match. Returns `:none` for anything else, including
  malformed input.
  """
  @callback discover(email :: String.t()) :: {:ok, config_id()} | :none

  @doc "Builds the URL that sends the browser to the identity provider."
  @callback authn_request(config_id(), authn_params()) ::
              {:ok, redirect_url :: String.t()} | {:error, term()}

  @doc """
  Validates a response and resolves it to a user who may be signed in.

  On success the user exists, is linked to this configuration, and is an active
  member of the configuration's organization with an up-to-date role. Owner
  roles are never granted or changed. Disabled memberships are never re-enabled.

  On failure the provider records `:sso_login_failed` in the audit log against
  the configuration's organization, with the reason in its metadata; the
  browser is only ever told that sign-in didn't complete.
  """
  @callback consume(config_id(), consume_params()) :: {:ok, User.t()} | {:error, term()}

  @doc "Service-provider metadata XML for a configuration."
  @callback sp_metadata(config_id(), %{acs_url: String.t()}) :: {:ok, String.t()} | :none

  @doc """
  Whether `user` may still sign in with a password or a magic link.

  `false` when any organization the user belongs to, and does not own, requires
  single sign-on. Owners always keep password access (break-glass).
  """
  @callback password_login_allowed?(User.t()) :: boolean()

  @doc "The organization's configuration, or `nil` when it has none."
  @callback get_config(organization_id :: term()) :: Config.t() | nil

  @doc """
  Creates or updates an organization's configuration.

  `attrs` has string keys:

    * `"idp_metadata"` - the identity provider's metadata XML, as pasted.
    * `"attribute_mapping"` - `%{"email" | "first_name" | "last_name" | "groups" => name}`;
      absent keys are unmapped (email then falls back to the subject).
    * `"role_mapping"` - `[{group, role}]`, evaluated in order.
    * `"default_role"` - `"admin" | "member" | "viewer"`.
    * `"default_team_id"` - a team ID as a string, or `nil`.

  Errors are keyed by those names (or `:base`). `opts` carries `:base_url`, the
  deployment's public base URL, from which a new configuration's entity ID is
  derived and against which a later host change is detected.
  """
  @callback put_config(organization_id :: term(), attrs :: map(), opts :: keyword()) ::
              {:ok, Config.t()} | {:error, errors()}

  @doc "Deletes an organization's configuration, its domains and its linked identities."
  @callback delete_config(organization_id :: term()) :: :ok | {:error, errors()}

  @doc "Turns enforcement on or off."
  @callback set_enforcement(organization_id :: term(), boolean()) ::
              {:ok, Config.t()} | {:error, errors()}

  @doc "Claims a domain for the organization, pending verification."
  @callback add_domain(organization_id :: term(), domain :: String.t()) ::
              {:ok, Domain.t()} | {:error, errors()}

  @doc "Checks a pending domain's DNS record and marks it verified."
  @callback verify_domain(organization_id :: term(), domain_id :: term()) ::
              {:ok, Domain.t()} | {:error, errors()}

  @doc "Removes a domain claim."
  @callback remove_domain(organization_id :: term(), domain_id :: term()) ::
              :ok | {:error, errors()}

  @doc """
  The organization's users who have signed in with SSO at least once, mapped to
  their most recent SSO sign-in.
  """
  @callback linked_users(organization_id :: term()) :: %{
              optional(term()) => DateTime.t() | nil
            }
end
